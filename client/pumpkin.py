"""A small Python client for the Cursed Pumpkin template on Tari Ootle (Esmeralda testnet).

It builds every game transaction by hand with ootle-py: stealth statements (outputs, balance proof, one-time spend
signatures) are made with the ootle-py crypto bridge, then handed to the game's template methods as call arguments.
The template is what spends the pumpkin, so a pass is only valid if it spends the commitment the game is tracking.

Nothing here touches mainnet: the network is pinned to Esmeralda and every key is a throwaway generated by this tool.
"""

