TARI = ResourceAddress(TARI_TOKEN)
GUESS_DOMAIN = b"cursed-pumpkin/guess/v1"
ZERO_MASK = Mask(b"\x00" * 32)

CRYPTO = load_default_provider()


# ------------------------------------------------------------------------------------------------ keys and encoding


def new_key() -> OotleSecretKey:
    return OotleSecretKey.random(NETWORK)


def key_to_json(k: OotleSecretKey) -> dict[str, str]:
    return {"owner_secret": k.owner_secret.hex(), "view_secret": k.view_secret.hex()}


def key_from_json(d: dict[str, str]) -> OotleSecretKey:
    return OotleSecretKey(NETWORK, bytes.fromhex(d["owner_secret"]), bytes.fromhex(d["view_secret"]))


def pk(k: OotleSecretKey) -> bytes:
    return k.public_keys().owner_pk


def account_of(k: OotleSecretKey) -> str:
    return str(k.to_address().to_component_address())


def lit(body: bytes) -> InstructionArgLiteral:
    return InstructionArgLiteral(body_hex=body.hex())


def a_amount(n: int) -> InstructionArgLiteral:
    return lit(cbor_encode_amount(n))


def a_u64(n: int) -> InstructionArgLiteral:
    return lit(cbor2.dumps(int(n)))


def a_str(s: str) -> InstructionArgLiteral:
    return lit(cbor_encode_str(s))


def a_bytes(b: bytes) -> InstructionArgLiteral:
    return lit(cbor2.dumps(bytes(b)))


def a_resource(r: str) -> InstructionArgLiteral:
    return lit(cbor_encode_resource_address(str(r)))


def statement_cbor(resource: str, statement: StealthTransferStatement) -> bytes:
    """CBOR of a StealthTransferStatement, exactly as the engine encodes it.

    ootle-py has no direct encoder for the statement, so we place it in a throwaway StealthTransfer instruction, let
    the bridge encode the whole transaction, and lift the statement out of the instruction. The bridge round-trip is
    checked to be byte-exact first, so the lifted bytes are the canonical encoding.
    """
    b = TransactionBuilder(NETWORK).with_max_epoch(1)
    b.add_instruction(StealthTransferInstruction(resource=ResourceAddress(resource), statement=statement))
    sk, _ = CRYPTO.generate_keypair()
    import base64

    raw = base64.b64decode(CRYPTO.bor_encode_transaction(CRYPTO.seal_transaction(b.build_unsigned().json, sk)))
    tree = cbor2.loads(raw)
    assert cbor2.dumps(tree) == raw, "CBOR round-trip is not byte-exact"
    instr = tree[1][0][0][0][2][0]
    assert instr[0] == 12, "expected the StealthTransfer instruction"
    return cbor2.dumps(instr[1][1])


def guess_commitment(game: str, guesser_pk: bytes, suspect_pk: bytes, salt: bytes) -> bytes:
    g = bytes.fromhex(game.removeprefix("component_"))
    return hashlib.sha256(GUESS_DOMAIN + g + guesser_pk + suspect_pk + salt).digest()


# ------------------------------------------------------------------------------------------------ transactions


class TxFailed(RuntimeError):
    pass


@dataclass
class Sent:
    label: str
    tx_id: str
    epoch: int
    accepted: bool
    fee: int | None
    upped: list[str]
    events: list[dict[str, Any]]
    reason: str | None = None

    @property
    def link(self) -> str:
        return f"{EXPLORER}/tx/{self.tx_id}"

    def to_json(self) -> dict[str, Any]:
        return {
            "label": self.label,
            "tx_id": self.tx_id,
            "link": self.link,
            "epoch": self.epoch,
            "accepted": self.accepted,
            "fee": self.fee,
            "upped": self.upped,
            "events": self.events,
            "reason": self.reason,
            "time_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        }


def connect(seal: OotleSecretKey, *others: OotleSecretKey) -> OotleClient:
    wallet = OotleWallet(default=LocalSigner(seal))
    for o in others:
        wallet.register(LocalSigner(o))
    return OotleClient.connect(INDEXER, wallet=wallet)


def builder(client: OotleClient, epochs: int = 20) -> TransactionBuilder:
    import secrets as _s

    return TransactionBuilder(NETWORK).with_max_epoch(client.get_epoch() + epochs).with_nonce(_s.randbits(32))


def send(
    client: OotleClient,
    label: str,
    b: TransactionBuilder,
    wants: set[Any],
    stealth_signers: list[tuple[OotleSecretKey, bytes]] | None = None,
    extra_inputs_from: UnsignedTransaction | None = None,
    dry_run_first: bool = True,
) -> Sent:
    """Resolve inputs, sign (stealth spend keys first, then the seal key), dry-run, send and wait."""
    unsigned = client.resolver.resolve(b.build_unsigned(), wants)
    if os.environ.get("PUMPKIN_DEBUG"):
        print(json.dumps(json.loads(unsigned.json), indent=1)[:4000])
    seal_pk = client.wallet.default_address.owner_pk
    auths = []
    for key, nonce in stealth_signers or []:
        auths.append(
            TransactionAuthorization(
                json=LocalSigner(key).add_stealth_signature(
                    unsigned.json, nonce, seal_pk, crypto=ensure_stealth_capable(CRYPTO)
                )
            )
        )
    req = TransactionRequest().with_transaction(unsigned)
    for a in auths:
        req = req.add_authorization(a)
    if dry_run_first:

        dry = client.send_dry_run(req)
        out = dry.outcome
        if out is None or not out.is_commit:
            raise TxFailed(f"{label}: dry run rejected: {out}")
        fr = (dry.raw or {}).get("finalize", {}).get("fee_receipt", {})
        need = (dry.raw or {}).get("finalize", {}).get("total_fees_required")
        if need is not None and fr.get("total_fees_paid", 0) < need:
            raise TxFailed(f"{label}: dry run pays {fr.get('total_fees_paid')} fees, needs {need}")
    sealed = client.seal_transaction(req)
    pending = client.send_transaction(sealed)
    outcome = pending.watch()
    receipt = None
    try:
        receipt = pending.get_receipt()
    except Exception:  # noqa: BLE001 - the receipt is informative
        pass
    upped = [u.substate_id.opaque for u in receipt.diff_summary.upped] if receipt else []
    events = []
    if receipt is not None:
        for e in getattr(receipt, "events", []) or []:
            try:
                events.append({"topic": e.topic, "payload": dict(e.payload)})
            except Exception:  # noqa: BLE001
                events.append({"repr": repr(e)[:300]})
    sent = Sent(
        label=label,
        tx_id=str(pending.tx_id),
        epoch=client.get_epoch(),
        accepted=bool(outcome.is_commit),
        fee=getattr(getattr(receipt, "fee_receipt", None), "total_fees_charged", None),
        upped=upped,
        events=events,
        reason=None if outcome.is_commit else str(getattr(outcome, "reason", outcome)),
    )
    print(f"  {label}: {'ok' if sent.accepted else 'REJECTED'} {sent.link}")
    if not sent.accepted:
        raise TxFailed(f"{label}: {sent.reason}")
    return sent


# ------------------------------------------------------------------------------------------------ stealth statements


def build_statement(
    client: OotleClient,
    resource: str,
    inputs: list[tuple[OotleSecretKey, bytes]],
    revealed_in: int,
    outputs: list[OotleSecretKey],
    revealed_out: tuple[int, bytes] | None,
) -> tuple[StealthTransferStatement, list[tuple[OotleSecretKey, bytes]], list[bytes]]:
    """Make a stealth transfer statement for the pumpkin.

    Returns the statement, the (spend key, sender nonce) pairs whose one-time keys must sign, and the commitments of
    the new outputs.
    """
    crypto = ensure_stealth_capable(CRYPTO)
    res = ResourceAddress(resource)
    outs = [Output(destination=o.to_address(), amount=1, resource_address=res) for o in outputs]
    revealed = RevealedOutput(revealed_out[0], revealed_out[1]) if revealed_out else None
    o = crypto.generate_outputs_statement(tuple(outs), revealed)
    signers: list[tuple[OotleSecretKey, bytes]] = []
    agg = ZERO_MASK
    if inputs:
        views = {k.to_address(): k for k, _ in inputs}
        if len({k.view_secret for k, _ in inputs}) != 1:
            raise ValueError("one input owner at a time")
        resolution = fetch_stealth_input_bodies(
            client=client,
            resource=res,
            inputs=[(k.to_address(), c) for k, c in inputs],
            crypto=crypto,
            view_secret=inputs[0][0].view_secret,
        )
        agg = resolution.agg_input_mask
        for req in resolution.required_signers:
            signers.append((views[req.signer], req.public_nonce))
    ins = StealthInputsStatement(
        inputs=tuple(StealthInput(commitment=c) for _, c in inputs), revealed_amount=revealed_in
    )
    proof = sign_balance_proof(
        crypto,
        input_mask=agg,
        output_mask=o.output_mask if o.statement.outputs else ZERO_MASK,
        inputs_statement=ins,
        outputs_statement=o.statement,
    )
    st = StealthTransferStatement(inputs_statement=ins, outputs_statement=o.statement, balance_proof=proof)
    crypto.validate_transfer(st)
    commitments = [bytes(x.output.commitment) if hasattr(x, "output") else bytes(x.commitment) for x in o.statement.outputs]
    return st, signers, commitments


def utxo_want(resource: str, commitment: bytes) -> Any:
    return WantInput.StealthCommitment(commitment=commitment, resource=ResourceAddress(resource))


def game_wants(game: str) -> set[Any]:
    from ootle import ComponentAddress

    c = ComponentAddress(game)
    return {WantInput.SpecificSubstate(id=SubstateId(opaque=game)), WantInput.AllComponentVaults(component=c)}


def account_fee(b: TransactionBuilder, payer: OotleSecretKey, fee: int) -> set[Any]:
    acc = account_of(payer)
    b.pay_fee_from_component(acc, fee)
    return {WantInput.SpecificSubstate(id=SubstateId(opaque=acc)), WantInput.VaultForResource(
        component=__import__("ootle").ComponentAddress(acc), resource=TARI)}


def read_component(client: OotleClient, addr: str) -> dict[str, Any]:
    s = client.get_substate(SubstateId(opaque=addr))
    return s


# ------------------------------------------------------------------------------------------------ raw instructions


@dataclass(frozen=True)
class RawInstruction:
    body: dict[str, Any]

    def to_json(self) -> dict[str, Any]:
        return self.body


def take_from_bucket(src: int, amount: int, dst: int) -> RawInstruction:
    return RawInstruction({"TakeFromBucket": {"input_bucket": {"id": src, "offset": None}, "amount": amount, "output_bucket": dst}})
